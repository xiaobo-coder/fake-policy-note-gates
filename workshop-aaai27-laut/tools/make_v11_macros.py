#!/usr/bin/env python3
"""Macros + table for the LAUT follow-up section, read only from the frozen v1.1 observer output
(v1.1/results/observer-test-001/observer.json). Create-only.
  python3 -I tools/make_v11_macros.py ../v1.1/results/observer-test-001/observer.json generated-v11"""
import hashlib, json, sys
from pathlib import Path
src, out = Path(sys.argv[1]), Path(sys.argv[2])
if out.exists(): sys.exit("exists (create-only)")
R = json.loads(src.read_text())
ARM = {"openai/gpt-oss-20b": ("Gptoss", "gpt-oss-20b"), "ollama:gemma4:12b-it-q4_K_M+nothink": ("Gemma", "Gemma-4-12B"),
       "ollama:qwen3:8b+nothink": ("QwenEight", "Qwen3-8B"), "ollama:qwen3.6:27b-coding-mtp-q4_K_M+nothink": ("Coder", "Qwen3.6-27B-cod."),
       "mlx:Qwen3.5-4B": ("QwenFour", "Qwen3.5-4B")}
# the frozen mlx model id is a local absolute path to the weights; match it by its last component
arm_key = lambda m: "mlx:" + Path(m[4:]).name if m.startswith("mlx:") else m
CN = {"J0": "Jzero", "J2": "Jtwo", "J2a": "Jtwoa", "J2b": "Jtwob", "J2c": "Jtwoc", "R": "Reg", "J2R": "JtwoReg"}
TN = {"H5_TA_J2_minus_J0": "HFive", "H6_TA_paraphrases_minus_J0": "HSix", "H7_TA_R_minus_J2": "HSeven", "H8_FA_J2R_minus_J0": "HEight"}
f3 = lambda x: "--" if x is None else (f"$-${abs(x):.3f}" if x < 0 else f"{x:.3f}")
fp = lambda x: "--" if x is None else ("$<$0.001" if x < 0.001 else f"{x:.3f}")
M = [f"% generated by tools/make_v11_macros.py from {src.name} (sha256 {hashlib.sha256(src.read_bytes()).hexdigest()[:16]}); do not edit"]
m = lambda k, v: M.append(f"\\newcommand{{\\V{k}}}{{{v}}}")
m("TruthProblems", len(R["truthProblems"])); m("Arms", len(R["runs"]))
m("ChainsOk", sum(1 for r in R["runs"] if r["chainOk"])); m("Reviews", sum(r["decisions"] for r in R["runs"]))
rows = []; nsup = {k: 0 for k in TN}
for r in R["runs"]:
    a, label = ARM[arm_key(r["model"])]; A = r["analysis"]
    m(a + "Gates", "pass" if A["gatesPass"] else "fail")
    for j, c in A["cells"].items():
        m(a + "TA" + CN[j], f3(c["trueApproval"])); m(a + "FA" + CN[j], f3(c["falseApproval"]))
    for k, t in A["tests"].items():
        if not t: continue
        n = TN[k]; m(a + n + "Diff", f3(t["meanFamilyDifference"])); m(a + n + "Holm", fp(t.get("pHolm"))); m(a + n + "Dec", t["decision"].replace("_", " ").lower())
        nsup[k] += t["decision"] == "SUPPORTED"
    C = A["cells"]; T = A["tests"]
    star = lambda k: "$^{*}$" if T[k] and T[k]["decision"] == "SUPPORTED" else ""
    rows.append(f"{label} & {f3(C['J0']['trueApproval'])} & {f3(C['J2']['trueApproval'])}{star('H5_TA_J2_minus_J0')} & "
                f"{f3((C['J2a']['trueApproval'] + C['J2b']['trueApproval'] + C['J2c']['trueApproval']) / 3)}{star('H6_TA_paraphrases_minus_J0')} & "
                f"{f3(C['R']['trueApproval'])}{star('H7_TA_R_minus_J2')} & {f3(C['J0']['falseApproval'])} & {f3(C['J2b']['falseApproval'])} & "
                f"{f3(C['J2R']['falseApproval'])}{star('H8_FA_J2R_minus_J0')} \\\\")
for k, n in TN.items(): m("NSup" + n, nsup[k])
out.mkdir(parents=True)
(out / "v11-macros.tex").write_text("\n".join(M) + "\n")
(out / "tab-v11.tex").write_text(M[0] + "\n\\begin{tabular}{@{}lccccccc@{}}\\toprule\n & \\multicolumn{4}{c}{True approval (compliant)} & \\multicolumn{3}{c}{False approval (violating)} \\\\"
    "\\cmidrule(lr){2-5}\\cmidrule(lr){6-8}\nGate & J0 & J2 & para. & R & J0 & J2b & J2+R \\\\\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\\end{tabular}\n")
print(len(M) - 1, "macros;", "supported:", nsup)
