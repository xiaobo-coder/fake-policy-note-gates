#!/usr/bin/env python3
"""Macros + table for the v1.2 gate-side defense comparison (P = provenance sentence, SP = spotlighting), read only from the
frozen v1.2 defense observer outputs (v1.2/results/observer-defense-*/observer.json). Create-only. Prefix \\X.
Rendering only: every decision, p, CI and drift verdict is copied from the observer; nothing is recomputed.
  python3 -I tools/make_v12d_macros.py ../v1.2/results generated-v12d"""
import hashlib, json, sys
from pathlib import Path
res, out = Path(sys.argv[1]), Path(sys.argv[2])
if out.exists(): sys.exit("exists (create-only)")
# (observer dir suffix, macro key, table label); order = table order
G = [("think", "QwenEightThink", "Qwen3-8B (thinking)"), ("gptoss", "Gptoss", "gpt-oss-20b"),
     ("ollama_gemma4-12b-it-q4_K_M-nothink", "Gemma", "Gemma-4-12B"), ("ollama_qwen3-8b-nothink", "QwenEight", "Qwen3-8B"),
     ("ollama_qwen3.6-27b-coding-mtp-q4_K_M-nothink", "Coder", "Qwen3.6-27B-cod."),
     ("mlx_Qwen3.5-4B", "QwenFour", "Qwen3.5-4B")]
f3 = lambda x: "--" if x is None else (f"$-${abs(x):.3f}" if x < 0 else f"{x:.3f}")
fp = lambda x: "--" if x is None else ("$<$0.001" if x < 0.001 else f"{x:.3f}")
DEC = {"SUPPORTED": "supported", "NOT_ESTABLISHED": "not established", "NON_INFORMATIVE": "non-informative", "EXPLORATORY": "exploratory"}
TK = {"D1_FA_J2bP_minus_J2b": "DOne", "D2_TA_J2P_minus_J2": "DTwo", "D3_FA_J2bSP_minus_J2b": "DThree", "D4_TA_J2SP_minus_J2": "DFour"}
M, rows, srcs = [], [], []
m = lambda k, v: M.append(f"\\newcommand{{\\X{k}}}{{{v}}}")
found = {}
for d in sorted(res.glob("observer-defense-*-001")):
    suf = d.name[len("observer-defense-"):-len("-001")]
    found[suf] = d / "observer.json"
unknown = set(found) - {g[0] for g in G}
if unknown:   # a gate name we did not anticipate: stop rather than silently drop it
    sys.exit(f"unknown defense observer(s): {sorted(unknown)}; add them to G")
nsup = {"P": 0, "SP": 0}; ngates = 0; ntest = {n: 0 for n in TK.values()}; nexpl = {n: 0 for n in TK.values()}; ndrift = 0
for suf, key, label in G:
    p = found.get(suf)
    if p is None or not p.exists():
        m(key + "Missing", "yes"); rows.append(f"{label} & \\multicolumn{{8}}{{c}}{{not run}} \\\\"); continue
    b = p.read_bytes(); R = json.loads(b); srcs.append(f"{p.parent.name}/observer.json {hashlib.sha256(b).hexdigest()}")
    ngates += 1
    C, T = R["cells"], R["tests"]; dr = R.get("drift")
    ta = lambda j: C.get(j, {}).get("trueApproval"); fa = lambda j: C.get(j, {}).get("falseApproval")
    CN = {"J0": "Jzero", "J2": "Jtwo", "J2b": "Jtwob", "R": "Reg", "J2P": "JtwoP", "J2SP": "JtwoSP", "J2bP": "JtwobP", "J2bSP": "JtwobSP"}   # LaTeX macro names cannot contain digits
    for j, n in CN.items():
        m(key + "TA" + n, f3(ta(j))); m(key + "FA" + n, f3(fa(j)))
    for k, n in TK.items():
        t = T.get(k)
        if not t: continue
        m(key + n + "Diff", f3(t["meanFamilyDifference"])); m(key + n + "P", fp(t.get("pHolm")))
        m(key + n + "CI", f"[{f3(t['ci95'][0])}, {f3(t['ci95'][1])}]" if t.get("ci95") else "--")
        m(key + n + "Dec", DEC.get(t["decision"], t["decision"].lower()) + (" (opposite direction)" if t.get("oppositeDirection") else ""))
        ntest[n] += t["decision"] == "SUPPORTED"; nexpl[n] += t["decision"] == "EXPLORATORY" and t.get("decisionIfDriftPassed") == "SUPPORTED"
    both = R.get("defendsBothDirections") or {}
    for d_ in ("P", "SP"):
        m(key + "Both" + d_, "yes" if both.get(d_) else "no"); nsup[d_] += bool(both.get(d_))
    m(key + "Gates", "pass" if R.get("gatesPass") else "fail")
    m(key + "Drift", "n/a" if dr is None else ("pass" if dr.get("pass") else "fail"))
    ndrift += dr is None or bool(dr.get("pass"))
    if dr is not None and dr.get("agreement") is not None: m(key + "DriftAgree", f"{dr['agreement']:.3f}")
    s = lambda k: "$^{*}$" if T.get(k) and T[k]["decision"] == "SUPPORTED" else ""
    dag = "" if dr is None or dr.get("pass") else "$^{\\dagger}$"
    rows.append(f"{label}{dag} & {f3(fa('J2b'))} & {f3(fa('J2bP'))}{s('D1_FA_J2bP_minus_J2b')} & {f3(fa('J2bSP'))}{s('D3_FA_J2bSP_minus_J2b')} & "
                f"{f3(ta('J0'))} & {f3(ta('J2'))} & {f3(ta('J2P'))}{s('D2_TA_J2P_minus_J2')} & {f3(ta('J2SP'))}{s('D4_TA_J2SP_minus_J2')} & {f3(ta('R'))} \\\\")
m("NGates", ngates); m("NBothP", nsup["P"]); m("NBothSP", nsup["SP"])
for n in TK.values(): m("NSup" + n, ntest[n]); m("NExplSup" + n, nexpl[n])
m("NDriftOk", ndrift)
head = "% generated by tools/make_v12d_macros.py; sources (sha256):\n" + "\n".join("% " + s_ for s_ in srcs) + "\n% do not edit"
tab = (head + "\n\\begin{tabular}{@{}lcccccccc@{}}\n\\toprule\n & \\multicolumn{3}{c}{FA (escalation, J2b)} & \\multicolumn{5}{c}{TA (obstruction, J2)} \\\\\n"
       "\\cmidrule(lr){2-4}\\cmidrule(l){5-9}\nGate & none & +P & +SP & J0 & none & +P & +SP & R \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
out.mkdir(parents=True)
(out / "v12d-macros.tex").write_text(head + "\n" + "\n".join(M) + "\n")
(out / "tab-v12d.tex").write_text(tab)
(out / "SOURCES.sha256").write_text("\n".join(srcs) + "\n")
print(len(M), "macros;", ngates, "gates")
