#!/usr/bin/env python3
"""Macros for v1.4 (hosted gates; H9, H10) from the frozen v1.4 observer output. Rendering only. Create-only. Prefix \\Z.
  python3 -I tools/make_v14_macros.py ../v1.4/results/observer-test-v14-001/observer.json generated-v14"""
import hashlib, json, sys
from pathlib import Path
src, out = Path(sys.argv[1]), Path(sys.argv[2])
if out.exists(): sys.exit("exists (create-only)")
b = src.read_bytes(); R = json.loads(b)
K = {"codex:openai.gpt-5.6-luna:high": "Luna", "codex:openai.gpt-6.1-terra:high": "Terra", "codex:openai.gpt-6.1-sol:high": "Sol"}
f3 = lambda x: "--" if x is None else (f"$-${abs(x):.3f}" if x < 0 else f"{x:.3f}")
fp = lambda x: "$<$0.001" if x < 0.001 else f"{x:.3f}"
M = [f"% generated by tools/make_v14_macros.py from {src.name} (sha256 {hashlib.sha256(b).hexdigest()[:16]}); do not edit"]
m = lambda k, v: M.append(f"\\newcommand{{\\Z{k}}}{{{v}}}")
nsup = 0
for r in R["runs"]:
    k = K[r["model"]]; C = r["cells"]
    for j, n in (("J0", "Jzero"), ("J2", "Jtwo"), ("J2b", "Jtwob")):
        m(k + "TA" + n, f3(C[j]["trueApproval"])); m(k + "FA" + n, f3(C[j]["falseApproval"]))
    for t, n in (("H9_FA_J2b_minus_J0", "HNine"), ("H10_TA_J2_minus_J0", "HTen")):
        T = r["tests"][t]; m(k + n + "Diff", f3(T["meanFamilyDifference"])); m(k + n + "P", fp(T["pHolm"])); m(k + n + "CI", f"[{f3(T['ci95'][0])}, {f3(T['ci95'][1])}]")
        if t.startswith("H9"): nsup += T["decision"] == "SUPPORTED"
    m(k + "Reviews", r["rows"])
m("NSupHNine", nsup); m("NGates", len(R["runs"]))
m("NViolating", R["runs"][0]["cells"]["J2b"]["n"] // 2)   # twins: half of each cell's items violate a rule
out.mkdir(parents=True); (out / "v14-macros.tex").write_text("\n".join(M) + "\n"); print(len(M) - 1, "macros")
