#!/usr/bin/env python3
"""Macros + table for v1.3 (registry defense R vs same-model neighbors: sanitizer, detector pipelines, R2/R3), read only from
the frozen v1.3 observer outputs (v1.3/results/observer-<P>-<gate>-001/observer.json). Rendering only: decisions, p, CIs,
drift verdicts copied from the observers. Create-only. Prefix \\Y. LaTeX macro names contain no digits.
  python3 -I tools/make_v13_macros.py ../v1.3/results test generated-v13"""
import hashlib, json, sys
from pathlib import Path
res, phase, out = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3])
if out.exists(): sys.exit("exists (create-only)")
G = [("ollama_qwen3-8b-nothink", "QwenEight", "Qwen3-8B"), ("ollama_gemma4-12b-it-q4_K_M-nothink", "Gemma", "Gemma-4-12B"),
     ("mlx_Qwen3.5-4B", "QwenFour", "Qwen3.5-4B"), ("gptoss", "Gptoss", "gpt-oss-20b")]
CN = {"J2": "Jtwo", "R": "Reg", "R2": "Regtwo", "R3": "Regthree", "J1": "Jone", "J2S": "JtwoS", "J2bS": "JtwobS", "J1S": "JoneS",
      "v11_J0": "Jzero", "v11_J2b": "Jtwob"}
TN = {"E1_TA_R_minus_J2S": "EOne", "E2_FA_R_minus_J2bS": "ETwo", "E3_TA_R23mean_minus_J2": "EThree"}
PN = {"raw": "Raw", "block": "Block", "escalate": "Esc", "strip": "Strip", "detectThenR": "DetR", "regexThenR": "RegexR"}
f3 = lambda x: "--" if x is None else (f"$-${abs(x):.3f}" if x < 0 else f"{x:.3f}")
fp = lambda x: "--" if x is None else ("$<$0.001" if x < 0.001 else f"{x:.3f}")
DEC = {"SUPPORTED": "supported", "NOT_ESTABLISHED": "not established", "NON_INFORMATIVE": "non-informative"}
M, rows, srcs = [], [], []
m = lambda k, v: M.append(f"\\newcommand{{\\Y{k}}}{{{v}}}")
nsup = {n: 0 for n in TN.values()}; ngates = 0; ndrift = 0
for suf, key, label in G:
    p = res / f"observer-{phase}-{suf}-001" / "observer.json"
    if not p.exists():
        rows.append(f"{label} & \\multicolumn{{7}}{{c}}{{not run}} \\\\"); continue
    b = p.read_bytes(); R = json.loads(b); srcs.append(f"{p.parent.name}/observer.json {hashlib.sha256(b).hexdigest()}"); ngates += 1
    C, T, P = R["cells"], R["tests"], R["pipelines"]
    ta = lambda j: (C.get(j) or {}).get("trueApproval"); fa = lambda j: (C.get(j) or {}).get("falseApproval")
    for j, n in CN.items(): m(key + "TA" + n, f3(ta(j))); m(key + "FA" + n, f3(fa(j)))
    for k, n in TN.items():
        t = T.get(k)
        if not t: continue
        m(key + n + "Diff", f3(t["meanFamilyDifference"])); m(key + n + "P", fp(t.get("pHolm"))); m(key + n + "CI", f"[{f3(t['ci95'][0])}, {f3(t['ci95'][1])}]")
        m(key + n + "Dec", DEC.get(t["decision"], t["decision"].lower()) + (" (opposite direction)" if t.get("oppositeDirection") else "")); nsup[n] += t["decision"] == "SUPPORTED"
    for inp in ("J2", "J2b"):
        for pk, pn in PN.items():
            q = P.get(f"{inp}_{pk}") or {}; nm = ("Jtwo" if inp == "J2" else "Jtwob") + pn
            m(key + nm + "TA", f3(q.get("TA"))); m(key + nm + "FA", f3(q.get("FA"))); m(key + nm + "Esc", f3(q.get("escalatedCompliant")))
    d = R["detector"]; m(key + "DetHitJtwo", f3(d["DJ2"]["flagRate"])); m(key + "DetHitJtwob", f3(d["DJ2b"]["flagRate"])); m(key + "DetFalseJone", f3(d["DJ1"]["flagRate"]))
    rc = R["residualClaims"]; m(key + "ResidJtwoS", f3(rc["J2S"]["stillMatchesClaimRegex"])); m(key + "ResidJtwobS", f3(rc["J2bS"]["stillMatchesClaimRegex"]))
    m(key + "Gates", "pass" if R["gatesPass"] else "fail"); dp = bool(R["drift"].get("pass")); m(key + "Drift", "pass" if dp else "fail"); ndrift += dp
    s = lambda k: "$^{*}$" if T.get(k) and T[k]["decision"] == "SUPPORTED" else ""
    dag = "" if dp else "$^{\\dagger}$"
    r23 = None if ta("R2") is None or ta("R3") is None else (ta("R2") + ta("R3")) / 2
    rows.append(f"{label}{dag} & {f3(ta('J2'))} & {f3(ta('J2S'))} & {f3(ta('R'))}{s('E1_TA_R_minus_J2S')} & {f3(r23)}{s('E3_TA_R23mean_minus_J2')} & "
                f"{f3(fa('J2bS'))} & {f3(fa('R'))}{s('E2_FA_R_minus_J2bS')} & {f3((P.get('J2b_detectThenR') or {}).get('FA'))} \\\\")
m("NGates", ngates); m("NDriftOk", ndrift)
for n in TN.values(): m("NSup" + n, nsup[n])
head = "% generated by tools/make_v13_macros.py; sources (sha256):\n" + "\n".join("% " + x for x in srcs) + "\n% do not edit"
tab = (head + "\n\\begin{tabular}{@{}lccccccc@{}}\n\\toprule\n & \\multicolumn{4}{c}{TA (waiver J2)} & \\multicolumn{3}{c}{FA (spoofed note J2b)} \\\\\n"
       "\\cmidrule(lr){2-5}\\cmidrule(l){6-8}\nGate & raw & sanit. & R & R2/R3 & sanit. & R & det.$\\to$R \\\\\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
out.mkdir(parents=True)
(out / "v13-macros.tex").write_text(head + "\n" + "\n".join(M) + "\n"); (out / "tab-v13.tex").write_text(tab)
(out / "SOURCES.sha256").write_text("\n".join(srcs) + "\n"); print(len(M), "macros;", ngates, "gates")
