#!/usr/bin/env python3
"""Macros (+ one table row in the tab-v11 column layout) for the v1.2 thinking-on follow-up, read only from the frozen v1.2
observer output (v1.2/results/observer-test-001/observer.json). Create-only. Prefix \\W (v1.1 uses \\V, v1.0 \\R).
  python3 -I tools/make_v12_macros.py ../v1.2/results/observer-test-001/observer.json generated-v12"""
import hashlib, json, statistics, sys
from pathlib import Path
src, out = Path(sys.argv[1]), Path(sys.argv[2])
if out.exists(): sys.exit("exists (create-only)")
R = json.loads(src.read_text()); r = R["runs"][0]; A = r["analysis"]
CN = {"J0": "Jzero", "J2": "Jtwo", "J2a": "Jtwoa", "J2b": "Jtwob", "J2c": "Jtwoc", "R": "Reg", "J2R": "JtwoReg"}
TN = {"H5_TA_J2_minus_J0": "HFive", "H6_TA_paraphrases_minus_J0": "HSix", "H7_TA_R_minus_J2": "HSeven", "H8_FA_J2R_minus_J0": "HEight", "H1r_FA_J2_minus_J0": "HOner"}
f3 = lambda x: "--" if x is None else (f"$-${abs(x):.3f}" if x < 0 else f"{x:.3f}")
fp = lambda x: "--" if x is None else ("$<$0.001" if x < 0.001 else f"{x:.3f}")
M = [f"% generated by tools/make_v12_macros.py from {src.name} (sha256 {hashlib.sha256(src.read_bytes()).hexdigest()[:16]}); do not edit"]
m = lambda k, v: M.append(f"\\newcommand{{\\W{k}}}{{{v}}}")
m("TruthProblems", len(R["truthProblems"])); m("ChainOk", "yes" if r["chainOk"] else "no"); m("Reviews", r["decisions"])
m("Gates", "pass" if A["gatesPass"] else "fail")
m("SysFail", A["systemFailures"]); m("Unparsed", A["unparsed"]); m("FinishLen", A["finishLength"])
m("ReasoningCalls", A["callsWithReasoning"])
RD = src.resolve().parent.parent.parent / r["run"]   # run path is relative to the v1.2 root
dec = [json.loads(l) for l in open(RD / "decisions.jsonl")]
ncond = len(json.load(open(RD / "config.json"))["conds"]); m("Items", r["decisions"] // ncond); m("Cells", ncond)
if dec: m("MedianSec", f"{statistics.median(d['ms'] for d in dec) / 1000:.1f}")
for j, c in A["cells"].items():
    m("TA" + CN[j], f3(c["trueApproval"])); m("FA" + CN[j], f3(c["falseApproval"]))
for k, t in {**A["tests"], **A["tests_v12"]}.items():
    if not t: continue
    n = TN[k]; m(n + "Diff", f3(t["meanFamilyDifference"])); m(n + "P", fp(t.get("pHolm", t["pTwoSided"]))); m(n + "Dec", t["decision"].replace("_", " ").lower())
C = A["cells"]; T = A["tests"]
star = lambda k: "$^{*}$" if T[k] and T[k]["decision"] == "SUPPORTED" else ""
row = (f"Qwen3-8B (thinking) & {f3(C['J0']['trueApproval'])} & {f3(C['J2']['trueApproval'])}{star('H5_TA_J2_minus_J0')} & "
       f"{f3((C['J2a']['trueApproval'] + C['J2b']['trueApproval'] + C['J2c']['trueApproval']) / 3)}{star('H6_TA_paraphrases_minus_J0')} & "
       f"{f3(C['R']['trueApproval'])}{star('H7_TA_R_minus_J2')} & {f3(C['J0']['falseApproval'])} & {f3(C['J2b']['falseApproval'])} & "
       f"{f3(C['J2R']['falseApproval'])}{star('H8_FA_J2R_minus_J0')} \\\\")
out.mkdir(parents=True)
(out / "v12-macros.tex").write_text("\n".join(M) + "\n")
(out / "tab-v12-row.tex").write_text(M[0] + "\n" + row + "\n")
print(len(M) - 1, "macros")
