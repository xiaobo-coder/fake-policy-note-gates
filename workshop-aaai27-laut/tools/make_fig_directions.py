#!/usr/bin/env python3
"""Headline figure: for each gate and condition, change vs J0 in true approval (x; < 0 = obstruction) and false approval
(y; > 0 = escalation). Descriptive. Reads only frozen observer outputs (v1.1, optionally the v1.2 defense observers).
Create-only. Rendering only.
  python3 -I tools/make_fig_directions.py ../v1.1/results/observer-test-001/observer.json generated-fig [V12_RESULTS_DIR]"""
import hashlib, json, sys
from pathlib import Path
src, out = Path(sys.argv[1]), Path(sys.argv[2]); v12 = Path(sys.argv[3]) if len(sys.argv) > 3 else None
if out.exists(): sys.exit("exists (create-only)")
# condition -> (group style, label). Groups: attack wordings, spoofed note, registry (platform-side), gate prompt defenses.
COND = {"J2": ("atk", "J2"), "J2a": ("atk", "J2a"), "J2c": ("atk", "J2c"), "J2b": ("spoof", "J2b"),
        "R": ("reg", "R"), "J2R": ("reg", "J2+R")}
DEF = {"J2P": ("def", "J2+P", "J2"), "J2SP": ("def", "J2+SP", "J2"), "J2bP": ("def", "J2b+P", "J2b"), "J2bSP": ("def", "J2b+SP", "J2b")}
# per-label placement so the labels near the origin do not collide (layout only)
POS = {"J2": "anchor=south east, yshift=6pt", "J2a": "anchor=south, yshift=10pt", "J2c": "anchor=north west, yshift=-8pt",
       "R": "anchor=north west, yshift=-2pt", "J2+R": "anchor=north east, xshift=-4pt, yshift=-8pt", "J2b": "anchor=west",
       "J2+P": "anchor=south west, xshift=2pt, yshift=6pt", "J2+SP": "anchor=north west, xshift=2pt, yshift=-10pt", "J2b+P": "anchor=west, xshift=3pt", "J2b+SP": "anchor=east, xshift=-3pt"}
b = src.read_bytes(); R = json.loads(b)
pts = {}   # label -> list of (dx, dy)
grp = {}
for r in R["runs"]:
    C = r["analysis"]["cells"]; t0, f0 = C["J0"]["trueApproval"], C["J0"]["falseApproval"]
    for j, (g, lab) in COND.items():
        c = C.get(j)
        if not c or c["trueApproval"] is None or c["falseApproval"] is None: continue
        pts.setdefault(lab, []).append((c["trueApproval"] - t0, c["falseApproval"] - f0)); grp[lab] = g
srcs = [f"{src} {hashlib.sha256(b).hexdigest()}"]
if v12:
    for d in sorted(v12.glob("observer-defense-*-001")):
        if d.name == "observer-defense-think-001": continue   # thinking arm is not in v1.1; keep the figure to the same five gates
        bb = (d / "observer.json").read_bytes(); X = json.loads(bb); srcs.append(f"{d.name}/observer.json {hashlib.sha256(bb).hexdigest()}")
        C = X["cells"]; t0, f0 = C["J0"]["trueApproval"], C["J0"]["falseApproval"]
        for j, (g, lab, _) in DEF.items():
            c = C.get(j)
            if c and c["trueApproval"] is not None and c["falseApproval"] is not None:
                pts.setdefault(lab, []).append((c["trueApproval"] - t0, c["falseApproval"] - f0)); grp[lab] = g
L = ["% generated by tools/make_fig_directions.py; sources (sha256):"] + ["% " + s for s in srcs] + ["% do not edit"]
for lab, ps in pts.items():
    g = grp[lab]
    L.append(f"\\addplot[only marks, dirpt{g}, forget plot] coordinates {{" + " ".join(f"({x:.3f},{y:.3f})" for x, y in ps) + "};")
    mx = sum(x for x, _ in ps) / len(ps); my = sum(y for _, y in ps) / len(ps)
    pos = POS.get(lab, "")
    L.append(f"\\addplot[only marks, dirmean{g}, forget plot] coordinates {{({mx:.3f},{my:.3f})}} node[dirlab{g}, {pos}] {{\\textsf{{{lab}}}}};")
out.mkdir(parents=True)
(out / "fig-directions-coords.tex").write_text("\n".join(L) + "\n")
print(len(pts), "conditions;", sum(len(v) for v in pts.values()), "points")
