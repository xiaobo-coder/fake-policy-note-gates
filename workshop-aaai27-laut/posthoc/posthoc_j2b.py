#!/usr/bin/env python3
"""POST HOC, NOT PREREGISTERED (written 2026-11-16 after the v1.1 results were known; J2b's escalation direction was already
seen in the v1.1 dev pilot before that freeze). Per gate: FA(J2b) - FA(J0) and TA(J2b) - TA(J0) on the frozen v1.1 test runs,
family-level differences over the 16 families, exact two-sided sign-flip test (the frozen v1.0 function, via the v1.1
observer), exact 95% CI by test inversion (the frozen v1.2 observer function), Holm over the five gates per measure.
Reads only frozen outputs; recomputes truth with the frozen rule interpreter. Create-only output.
  python3 -I posthoc/posthoc_j2b.py ../v1.1/results posthoc/out-j2b-001"""
import importlib.util, json, os, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent; ROOT = HERE.parent.parent
spec = importlib.util.spec_from_file_location('observe_v12d', ROOT / 'v1.2' / 'observer' / 'observe_v12d.py')
D = importlib.util.module_from_spec(spec); spec.loader.exec_module(D)
M = D.M; O = M.O
res, out = Path(sys.argv[1]), Path(sys.argv[2])
if out.exists(): sys.exit("exists (create-only)")
ds = json.load(open(res / 'dataset-f11-002' / 'dataset.json', encoding='utf-8'))
truth = {it['id']: ('unsafe' if O.violations(it['rules'], it['record']) else 'safe') for it in ds}
assert all(truth[it['id']] == it['kind'] for it in ds), "truth mismatch"
fam_of = {it['id']: it['family'] for it in ds}
GATES = [("gptoss", "Gptoss"), ("ollama_gemma4-12b-it-q4_K_M-nothink", "Gemma"), ("ollama_qwen3-8b-nothink", "QwenEight"),
         ("ollama_qwen3.6-27b-coding-mtp-q4_K_M-nothink", "Coder"), ("mlx_Qwen3.5-4B", "QwenFour")]
rep = {"note": "post hoc, not preregistered; descriptive inference", "gates": {}}
for suf, key in GATES:
    run = res / f"test-{suf}-001"; ok, n, why = O.verify_chain(str(run))
    if not ok: sys.exit(f"chain fail {run}: {why}")
    rows = [json.loads(l) for l in open(run / 'decisions.jsonl', encoding='utf-8')]
    valid = [r for r in rows if not r['systemFailure'] and r['decision'] in ('approve', 'reject')]
    g = {"run": str(run), "calls": n}
    for kind, lab in (("unsafe", "FA"), ("safe", "TA")):
        x = M.fam_rates(valid, truth, fam_of, 'J2b', kind); y = M.fam_rates(valid, truth, fam_of, 'J0', kind)
        fams = sorted(set(x) & set(y)); d = [x[f] - y[f] for f in fams]
        mdiff, p = O.sign_flip(d)
        g[lab] = {"families": len(fams), "meanFamilyDifference": mdiff, "pTwoSided": p, "ci95": D.signflip_ci(d)}
    rep["gates"][key] = g
for lab in ("FA", "TA"):
    ks = list(rep["gates"]); ps = [rep["gates"][k][lab]["pTwoSided"] for k in ks]
    for k, ph in zip(ks, O.holm(ps)): rep["gates"][k][lab]["pHolm"] = ph
out.mkdir(parents=True)
(out / "posthoc-j2b.json").write_text(json.dumps(rep, indent=1))
f3 = lambda v: f"$-${abs(v):.3f}" if v < 0 else f"{v:.3f}"
fp = lambda v: "$<$0.001" if v < 0.001 else f"{v:.3f}"
L = ["% POST HOC, generated by posthoc/posthoc_j2b.py; do not edit"]
for k, g in rep["gates"].items():
    for lab in ("FA", "TA"):
        t = g[lab]; L += [f"\\newcommand{{\\P{k}{lab}Diff}}{{{f3(t['meanFamilyDifference'])}}}",
                         f"\\newcommand{{\\P{k}{lab}CI}}{{[{f3(t['ci95'][0])}, {f3(t['ci95'][1])}]}}",
                         f"\\newcommand{{\\P{k}{lab}P}}{{{fp(t['pHolm'])}}}"]
L.append(f"\\newcommand{{\\PNFASig}}{{{sum(g['FA']['pHolm'] < 0.05 for g in rep['gates'].values())}}}")
L.append(f"\\newcommand{{\\PFAPMax}}{{{fp(max(g['FA']['pHolm'] for g in rep['gates'].values()))}}}")
(out / "posthoc-j2b-macros.tex").write_text("\n".join(L) + "\n")
print(json.dumps({k: {lab: (round(g[lab]['meanFamilyDifference'], 3), [round(c, 3) for c in g[lab]['ci95']], round(g[lab]['pHolm'], 4)) for lab in ("FA", "TA")} for k, g in rep["gates"].items()}, indent=1))
